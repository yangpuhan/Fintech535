"""
Bake the book into docs/book.js, which is all the published page loads.

    python -m covered_call.build

GitHub Pages serves files and nothing else — there is no server to run a
backtest on request — so the whole run is computed here, once, and written
out as one JSON blob on `window.BOOK`. The page is hand-written HTML/CSS/JS
and reads that blob. No Node, no build step, nothing to install.

The page is *not* generated from Python. Assignment 1.1 rendered its figures
server-side and shipped figure specs; this one ships data and lets the page
draw. It is less code and it means the numbers on the page and the numbers in
the tables are the same objects.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from .book import (INITIAL_RATE, MAINT_RATE, OPENING_CASH, load, option_frame,
                   run, stock_series)
from .fit import analyse, order_bar_evidence

DOCS = Path(__file__).resolve().parents[1] / "docs"
SCATTER_POINTS = 2500


def _clean(obj):
    """NaN is not JSON. Numpy scalars are not JSON either."""
    if isinstance(obj, dict):
        return {k: _clean(v) for k, v in obj.items() if not k.startswith("_")}
    if isinstance(obj, (list, tuple)):
        return [_clean(v) for v in obj]
    if isinstance(obj, (np.integer,)):
        return int(obj)
    if isinstance(obj, (np.floating, float)):
        return None if not np.isfinite(obj) else float(obj)
    if isinstance(obj, (np.bool_,)):
        return bool(obj)
    if obj is pd.NaT or (obj is not None and obj is pd.NA):
        return None
    return obj


def bundle() -> dict:
    raw = load()
    res = run(raw)
    opts = option_frame(raw)
    stock = stock_series(raw)

    fit = analyse(opts, stock, max_points=SCATTER_POINTS)
    order_bars = order_bar_evidence(opts, res.weeks)

    # how much the mid-fill assumption was actually worth on the book's own
    # ten orders: positive means the tape printed above our sell, i.e. the
    # fill we assumed was conservative
    vs = [o["vs_mid"] for o in order_bars if o["vs_mid"] is not None]
    fit["order_bar"] = {
        "n": len(order_bars),
        "n_traded": len(vs),
        "mean_vs_mid": float(np.round(np.mean(vs), 4)) if vs else None,
        "total_dollars": float(np.round(np.sum(vs) * 100, 2)) if vs else None,
        "min_volume": int(min(o["volume"] for o in order_bars if o["volume"])),
        "max_volume": int(max(o["volume"] for o in order_bars if o["volume"])),
    }

    px = stock["TRDPRC_1"]
    return {
        "meta": {
            "ticker": raw["ticker"],
            "stock_ric": raw["stock_ric"],
            "interval": raw["interval"],
            "order_hour_utc": raw["order_hour_utc"],
            "fetched_at": raw["fetched_at"],
            "synthetic": raw["synthetic"],
            "first_bar": str(stock.index.min()),
            "last_bar": str(stock.index.max()),
            "n_bars": int(len(stock)),
            "n_sessions": int(len({t.date() for t in stock.index})),
            "n_contracts": int(opts["ric"].nunique()),
            "n_option_bars": int(len(opts)),
            "chain": [{"expiry": str(c["expiry"]), "requested": c["requested"],
                       "resolved": c["resolved"]} for c in raw["chain"]],
            # The one fact on the page that is not derived from the tape.
            # LSEG TR.EPSActReportDate for AAPL.O over this window returns a
            # single row: 2026-07-30 16:31, i.e. after the close on the
            # Thursday, one session before the 31 Jul expiry. The strike rule
            # has no term that knows this, which is the point of section 07.
            "earnings": {"ts": "2026-07-30 16:31:00", "eps": 1.91,
                         "source": "LSEG TR.EPSActReportDate / TR.EPSActValue"},
            "initial_rate": INITIAL_RATE,
            "maint_rate": MAINT_RATE,
            "opening_cash": OPENING_CASH,
            "contract": 100,
        },
        "stats": res.stats,
        "blotter": [vars(f) | {"ts": str(f.ts)} for f in res.blotter],
        "ledger": res.ledger,
        "weeks": res.weeks,
        "skipped": res.skipped,
        "fit": fit,
        "order_bars": order_bars,
        "stock": {
            "ts": [str(t) for t in stock.index],
            "px": [None if pd.isna(v) else float(np.round(v, 4)) for v in px],
        },
    }


def main() -> Path:
    data = bundle()
    DOCS.mkdir(parents=True, exist_ok=True)
    (DOCS / ".nojekyll").write_text("", encoding="utf-8")

    payload = json.dumps(_clean(data), separators=(",", ":"))
    out = DOCS / "book.js"
    out.write_text(
        "/* Generated by `python -m covered_call.build` — do not edit. */\n"
        f"window.BOOK = {payload};\n", encoding="utf-8")

    s = data["stats"]
    print(f"wrote {out}  ({out.stat().st_size / 1024:.0f} KB)")
    print(f"  {s['weeks_traded']} weeks traded, {s['weeks_skipped']} skipped, "
          f"{s['n_assigned']} assigned, {s['n_expired']} expired")
    print(f"  NAV {s['opening_cash']:,.2f} -> {s['final_nav']:,.2f} "
          f"({s['ret_pct']:+.2f}%), buy-and-hold {s['bh_ret_pct']:+.2f}%")
    print(f"  attribution gap {s['attribution_gap']:+.2f}  "
          f"min available {s['min_available']:,.2f}")
    print(f"  fit R2 {data['fit']['overall']['r2']} on "
          f"{data['fit']['overall']['n']} pairs")
    return out


if __name__ == "__main__":
    main()
